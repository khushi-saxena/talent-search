// Regenerates src/lib/vocab.ts from the candidate data, so the model can only
// pick values that actually exist.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("data/candidates.json", "utf8"));
const uniq = (f) => [...new Set(data.flatMap(f))].sort();
const cityStates = {};
for (const c of data) cityStates[c.location.city] = c.location.state;

const v = {
  ROLES: uniq((c) => [c.role]),
  SENIORITY: ["junior", "mid", "senior", "staff"],
  CITIES: uniq((c) => [c.location.city]),
  SKILLS: uniq((c) => c.skills),
  COMPANIES: uniq((c) => c.experiences.map((e) => e.company)),
  COMPANY_TYPES: uniq((c) => c.experiences.map((e) => e.company_type)),
  SCHOOLS: uniq((c) => c.education.map((e) => e.school)),
  DEGREES: uniq((c) => c.education.map((e) => e.degree)),
  FIELDS: uniq((c) => c.education.map((e) => e.field)),
};

let out = "// Generated by scripts/vocab.mjs from data/candidates.json. Do not edit.\n\n";
for (const [k, vals] of Object.entries(v)) {
  out += `export const ${k} = ${JSON.stringify(vals, null, 2)} as const;\n\n`;
}
out += `export const CITY_STATE: Record<string, string> = ${JSON.stringify(cityStates, null, 2)};\n`;
writeFileSync("src/lib/vocab.ts", out);
console.log("wrote src/lib/vocab.ts");
